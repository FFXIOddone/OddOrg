return function(t)
    local function start(scope)
        t.get("handle_ephemeral")({ "/oddorg", "ephemeral", "dump", scope or "all" })
        local state = t.get("ephemeral")
        assert(state.running, state.error or "crystal queue did not start")
        return state
    end

    local function tick()
        t.get("run_ephemeral_tick")()
    end

    t.test("two stored stacks cycle through one free Inventory slot", function()
        t.capacity(0, 2)
        t.put(0, 1, 4097, 12, 1)
        t.put(5, 1, 4096, 12)
        t.put(5, 2, 4096, 12)
        local state = start("storage")

        tick()
        assert(#t.moves() == 1 and t.moves()[1].source_index == 1)
        t.put(5, 1, nil)
        t.put(0, 2, 4096, 12)
        tick()
        t.advance(1)
        tick()
        assert(#t.trades() == 1 and #t.trades()[1].entries == 1)

        t.put(0, 2, nil)
        tick()
        t.advance(10)
        tick()
        assert(#t.moves() == 2 and t.moves()[2].source_index == 2)
        assert(state.running)
        t.select_target(0)
        t.put(5, 2, nil)
        t.put(0, 2, 4096, 12)
        t.advance(1)
        tick()
        assert(#t.trades() == 2 and #t.trades()[2].entries == 1)
        t.put(0, 2, nil)
        t.advance(10)
        tick()
        assert(not state.running and t.get("container_item_count")(5, 4096) == 0)
    end)

    t.test("retained Moogle remains usable after target selection is lost", function()
        t.put(0, 1, 4096, 12)
        start("inventory")
        t.select_target(0)
        tick()
        assert(#t.trades() == 1)
        assert(t.trades()[1].target.index == 7)
        assert(t.trades()[1].target.server_id == 1007)
    end)

    t.test("preexisting matching Inventory stack cannot confirm a rejected stage", function()
        t.capacity(0, 2)
        t.put(0, 1, 4096, 12)
        t.put(5, 1, 4096, 12)
        local state = start("storage")
        tick()
        assert(#t.moves() == 1 and state.cursor == 1)

        tick()
        assert(#t.trades() == 0 and state.running)
        t.advance(6)
        tick()
        assert(#t.moves() == 1 and #t.trades() == 0)
        assert(not state.running and state.cursor == 1)
    end)

    t.test("partial trade observation stops without resend", function()
        t.put(0, 1, 4096, 12)
        t.put(0, 2, 4097, 12)
        local state = start("inventory")
        tick()
        assert(#t.trades() == 1 and #t.trades()[1].entries == 2)

        t.put(0, 1, nil)
        t.advance(16)
        tick()
        assert(not state.running and state.cursor == 1)
        assert(#t.trades() == 1)
        tick()
        assert(#t.trades() == 1)
        assert(state.error and state.error:find("partially observed", 1, true))
        t.get("handle_ephemeral")({ "/oddorg", "ephemeral", "dump", "inventory" })
        assert(state.running and state.awaiting_trade == nil)
        tick()
        assert(#t.trades() == 2 and t.trades()[2].entries[1].item_id == 4097)
    end)

    t.test("removing another stack cannot confirm the selected deposit", function()
        t.reset({ ["4096"] = 12 })
        t.put(0, 1, 4096, 12)
        t.put(0, 2, 4096, 12)
        local state = start("inventory")
        tick()
        assert(#t.trades() == 1 and t.trades()[1].entries[1].source_index == 2)
        t.put(0, 1, nil)
        t.advance(16)
        tick()
        assert(not state.running and state.cursor == 1 and state.error)
    end)

    t.test("completion waits for both observed deposit and animation", function()
        t.put(0, 1, 4096, 12)
        local state = start("inventory")
        tick()
        assert(#t.trades() == 1 and state.cursor == 1)

        t.put(0, 1, nil)
        tick()
        assert(state.running and state.cursor == 1)
        t.advance(9)
        tick()
        assert(state.running and state.cursor == 1)
        t.advance(1)
        tick()
        assert(not state.running and state.cursor == 2)
        assert(#t.trades() == 1)
    end)

    t.test("character change invalidates pending deposit without retry", function()
        t.put(0, 1, 4096, 12)
        local state = start("inventory")
        tick()
        assert(#t.trades() == 1)
        t.character("Alt", 43)
        tick()
        assert(not state.running and state.cursor == 1)
        assert(#t.trades() == 1)
        assert(state.error and state.error:find("character changed", 1, true))
    end)

    t.test("keep eighteen deposits only six from stored split", function()
        t.reset({ ["4096"] = 18 })
        t.put(0, 1, 4096, 12)
        t.put(5, 1, 4096, 12)
        local state = start("all")

        tick()
        assert(#t.moves() == 1 and t.moves()[1].quantity == 6)
        t.put(5, 1, 4096, 6)
        t.put(0, 2, 4096, 6)
        tick()
        t.advance(1)
        tick()
        assert(#t.trades() == 1)
        assert(#t.trades()[1].entries == 1 and t.trades()[1].entries[1].quantity == 6)

        t.put(0, 2, nil)
        tick()
        t.advance(10)
        tick()
        assert(not state.running)
        assert(t.get("container_item_count")(0, 4096) == 12)
        assert(t.get("container_item_count")(5, 4096) == 6)
    end)
end
